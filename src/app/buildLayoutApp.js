function getLiveStatusTone({ micError, isMicActive, isModelReady }) {
  if (micError) return 'danger';
  if (isMicActive) return 'live';
  if (isModelReady) return 'ready';
  return 'idle';
}

function getActiveProfileLabel({ streamingSnapshot, streamingPresets, profileId }) {
  return streamingSnapshot?.profileId === 'custom'
    ? 'Custom'
    : streamingPresets.find((preset) => preset.id === profileId)?.label ?? 'Custom';
}

